const LITTLE_ENDIAN = new Uint8Array(new Uint32Array([1]).buffer)[0] === 1;

export function buildRgbaTable(name = 'colodore') {
  const palette = PALETTES[name] || PALETTES.colodore;
  const table = new Uint32Array(16);
  for (let i = 0; i < 16; i++) {
    const [r, g, b] = palette[i];
    table[i] = LITTLE_ENDIAN ? ((0xff << 24) | (b << 16) | (g << 8) | r) >>> 0 : ((r << 24) | (g << 16) | (b << 8) | 0xff) >>> 0;
  }
  return table;
}
